"""Executive Decision Narrator for What-If AI.

Transforms quantitative outputs from whatif_engine into clear, actionable
executive summaries and strategic recommendations for retail managers.

Strict Rule:
    The narrator NEVER calculates numbers. It formats and synthesizes the exact
    outputs generated by whatif_engine into structured business prose.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from src.agents.schemas import ExecutiveNarrative


def format_currency_vnd(amount: float) -> str:
    """Format numerical currency into formatted VND string.

    Args:
        amount: Numerical amount in VND.

    Returns:
        str: Comma-separated currency string (e.g. '455,000,000 VND').
    """
    return f"{amount:,.0f} VND"


class DecisionNarrator:
    """Narrator creating executive business reports from deterministic simulation outputs."""

    def __init__(self, api_key: Optional[str] = None) -> None:
        """Initialize the decision narrator.

        Args:
            api_key: Optional API key for LLM services.
        """
        self.api_key = api_key

    def synthesize(self, result: Dict[str, Any]) -> ExecutiveNarrative:
        """Synthesize quantitative analysis into a structured ExecutiveNarrative.

        Args:
            result: Result dictionary returned by whatif_engine.analyse().

        Returns:
            ExecutiveNarrative: Structured executive summary with headline, findings,
                risk assessment, and recommendations.
        """
        prod_id = result.get("product_id", "N/A")
        prod_name = result.get("product_name", "Sản phẩm")
        price_change = result.get("price_change", 0.0)
        base = result.get("baseline", {})
        mc = result.get("monte_carlo", {})
        scenarios = result.get("scenarios", {})
        be = result.get("breakeven_elasticity")
        warnings = result.get("warnings", [])
        reverse_res = result.get("reverse_what_if")

        base_profit = float(scenarios.get("baseline", {}).get("profit", 0.0))
        expected_profit = float(scenarios.get("expected", {}).get("profit", 0.0))
        profit_diff = expected_profit - base_profit
        profit_pct = (profit_diff / base_profit * 100.0) if abs(base_profit) > 1e-6 else 0.0

        prob_beat = float(mc.get("prob_profit_above_baseline", 0.0))

        # 1. Headline synthesis
        if price_change > 0:
            change_str = f"tăng giá {price_change:+.0%}"
        elif price_change < 0:
            change_str = f"giảm giá {price_change:+.0%}"
        else:
            change_str = "giữ nguyên giá"

        if profit_pct > 0:
            headline = (
                f"Đề xuất {change_str} cho {prod_name} ({prod_id}) dự kiến cải thiện lợi nhuận "
                f"+{profit_pct:.1f}% (xác suất thành công: {prob_beat:.0%})."
            )
        else:
            headline = (
                f"Cảnh báo: Đề xuất {change_str} cho {prod_name} ({prod_id}) có nguy cơ làm xói mòn "
                f"lợi nhuận {profit_pct:.1f}% (xác suất vượt cơ sở chỉ đạt {prob_beat:.0%})."
            )

        # 2. Key findings synthesis
        key_findings: List[str] = [
            (
                f"Lợi nhuận kỳ vọng tháng tới ước đạt {format_currency_vnd(expected_profit)} "
                f"so với mức cơ sở {format_currency_vnd(base_profit)} (thay đổi {profit_pct:+.1f}%)."
            ),
            (
                f"Mô phỏng Monte Carlo (10.000 lượt): Dải lợi nhuận an toàn 90% dao động từ "
                f"{format_currency_vnd(float(mc.get('profit_p5', 0.0)))} (kịch bản bi quan p5) đến "
                f"{format_currency_vnd(float(mc.get('profit_p95', 0.0)))} (kịch bản lạc quan p95)."
            ),
        ]

        if "optimistic" in scenarios and "pessimistic" in scenarios:
            opt_prof = float(scenarios["optimistic"]["profit"])
            pess_prof = float(scenarios["pessimistic"]["profit"])
            key_findings.append(
                f"Khoảng dao động kinh tế lượng: Nếu khách hàng ít nhạy giá, lợi nhuận đạt "
                f"{format_currency_vnd(opt_prof)}; nếu khách hàng rất nhạy giá, lợi nhuận đạt "
                f"{format_currency_vnd(pess_prof)}."
            )

        # 3. Risk assessment synthesis
        risk_parts: List[str] = []
        if be is not None:
            risk_parts.append(
                f"Độ co giãn hòa vốn là {be:.2f}. Nếu người tiêu dùng phản ứng nhạy giá hơn ngưỡng này, "
                f"quyết định điều chỉnh giá sẽ bắt đầu gây thua lỗ so với hiện tại."
            )
        if prob_beat < 0.50:
            risk_parts.append(
                "Rủi ro suy giảm doanh thu và lợi nhuận ở mức cao (>50% khả năng không đạt lợi nhuận cơ sở)."
            )
        elif prob_beat >= 0.80:
            risk_parts.append(
                "Mức độ rủi ro thấp: Có tới trên 80% khả năng quyết định mang lại giá trị thặng dư ròng."
            )
        else:
            risk_parts.append(
                "Mức độ rủi ro trung bình: Quyết định phụ thuộc vào diễn biến sức mua và đối thủ cạnh tranh."
            )

        if warnings:
            risk_parts.append("Cảnh báo kỹ thuật: " + "; ".join(warnings))

        risk_assessment = " ".join(risk_parts)

        # 4. Strategic recommendation
        if reverse_res and reverse_res.get("best_options"):
            top_opt = reverse_res["best_options"][0]
            recommendation = (
                f"Khuyến nghị Tối ưu hóa ngược: Để đạt mục tiêu tăng trưởng "
                f"+{reverse_res['target_growth']:.0%}, phương án tối ưu nhất là điều chỉnh giá "
                f"{top_opt['price_change']:+.0%} (đạt {format_currency_vnd(top_opt['new_price'])}), "
                f"mang lại xác suất đạt chỉ tiêu {top_opt['prob_success']:.0%} "
                f"với lợi nhuận kỳ vọng {format_currency_vnd(top_opt['expected_profit'])}."
            )
        elif profit_pct > 5.0 and prob_beat >= 0.70:
            recommendation = (
                f"Khuyến nghị triển khai: Đề xuất điều chỉnh giá khả thi và có đòn bẩy lợi nhuận rõ rệt. "
                f"Nên theo dõi chặt chẽ phản ứng của thị trường trong 2 tuần đầu tiên."
            )
        elif profit_pct <= 0:
            recommendation = (
                f"Khuyến nghị cân nhắc lại: Không nên triển khai mức giá này vì áp lực giảm sản lượng "
                f"lớn hơn biên lợi nhuận bù đắp. Hãy thử nghiệm Reverse What-If để tìm mức giá cân bằng hơn."
            )
        else:
            recommendation = (
                f"Khuyến nghị thử nghiệm cục bộ: Mức tăng lợi nhuận khiêm tốn ({profit_pct:+.1f}%). "
                f"Nên kiểm tra độ co giãn chéo với các sản phẩm thay thế trước khi áp dụng trên diện rộng."
            )

        return ExecutiveNarrative(
            headline=headline,
            key_findings=key_findings,
            risk_assessment=risk_assessment,
            recommendation=recommendation,
        )
