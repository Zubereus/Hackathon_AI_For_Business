"""Data validation test suite for Phase 1 Data Pipeline.

Verifies that the synthetic retail dataset generated by whatif_engine.data_generator:
    1. Contains zero null or NaN values across all columns.
    2. Enforces strictly non-negative financial values (price > 0, cost >= 0, sales_volume >= 0).
    3. Fully complies with Pydantic schema validation (RetailSalesRecord).
    4. Conforms to the fundamental Law of Demand (inverse relationship between price and quantity).
    5. Correctly reflects promotional lifts and calendar structure (365 days across 3 products).

Strict Rules:
    - 100% Type Hints and Google-style docstrings.
    - Zero LLM math: All checks use deterministic NumPy, Pandas, and SciPy assertions.
"""

from __future__ import annotations

from typing import List
import numpy as np
import pandas as pd
import pytest

from whatif_engine.data_generator import generate_retail_data
from whatif_engine.schemas import RetailSalesRecord


@pytest.fixture(scope="module")
def generated_dataset() -> pd.DataFrame:
    """Fixture generating a 365-day dataset for 3 products with fixed seed.

    Returns:
        pd.DataFrame: Deterministic synthetic retail sales DataFrame.
    """
    return generate_retail_data(n_days=365, random_state=42)


def test_data_no_nulls(generated_dataset: pd.DataFrame) -> None:
    """Verify that the generated dataset contains zero null, NaN, or None values.

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    assert not generated_dataset.empty, "Dataset must not be empty."
    null_counts = generated_dataset.isna().sum()
    for col, count in null_counts.items():
        assert count == 0, f"Column '{col}' contains {count} null/NaN values."


def test_non_negative_values(generated_dataset: pd.DataFrame) -> None:
    """Ensure price, cost, and sales_volume contain strictly non-negative values.

    Rules checked:
        - price must be strictly positive (> 0).
        - cost must be non-negative (>= 0).
        - sales_volume must be non-negative (>= 0).

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    # 1. Price must be strictly positive
    invalid_prices = generated_dataset[generated_dataset["price"] <= 0.0]
    assert len(invalid_prices) == 0, (
        f"Found {len(invalid_prices)} records with price <= 0."
    )

    # 2. Cost must be non-negative
    invalid_costs = generated_dataset[generated_dataset["cost"] < 0.0]
    assert len(invalid_costs) == 0, (
        f"Found {len(invalid_costs)} records with cost < 0."
    )

    # 3. Sales volume must be non-negative
    invalid_volumes = generated_dataset[generated_dataset["sales_volume"] < 0.0]
    assert len(invalid_volumes) == 0, (
        f"Found {len(invalid_volumes)} records with sales_volume < 0."
    )

    # 4. Economic sanity: price must exceed cost
    loss_records = generated_dataset[generated_dataset["price"] <= generated_dataset["cost"]]
    assert len(loss_records) == 0, (
        f"Found {len(loss_records)} records where price <= cost."
    )


def test_schema_compliance(generated_dataset: pd.DataFrame) -> None:
    """Verify that every record in the dataset strictly complies with RetailSalesRecord schema.

    Iterates through rows and parses into Pydantic models to ensure type safety,
    date format validity, and constraint enforcement.

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    records_dict: List[dict] = generated_dataset.to_dict(orient="records")
    assert len(records_dict) == 1095, f"Expected 1095 records, got {len(records_dict)}."

    validated_count = 0
    for row in records_dict:
        # Pydantic will raise ValidationError if any field violates contract
        record = RetailSalesRecord(**row)
        assert record.price > 0.0
        assert record.cost >= 0.0
        assert record.sales_volume >= 0.0
        assert record.promotion_flag in (0, 1)
        validated_count += 1

    assert validated_count == len(records_dict), "All records must successfully validate."


def test_dataset_shape_and_products(generated_dataset: pd.DataFrame) -> None:
    """Ensure dataset contains exactly 365 days for each of the 3 specified products.

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    expected_products = {"PROD_01", "PROD_02", "PROD_03"}
    actual_products = set(generated_dataset["product_id"].unique())
    assert actual_products == expected_products, (
        f"Expected products {expected_products}, found {actual_products}."
    )

    for pid in expected_products:
        prod_subset = generated_dataset[generated_dataset["product_id"] == pid]
        assert len(prod_subset) == 365, (
            f"Product {pid} has {len(prod_subset)} days of data instead of 365."
        )


def test_law_of_demand_inverse_relationship(generated_dataset: pd.DataFrame) -> None:
    """Verify the economic law of demand: lower price leads to higher sales volume.

    For each product, partitions days by price tier (discounted vs regular/premium)
    and asserts that mean sales volume at lower price exceeds mean sales volume at higher price.

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    for pid in ["PROD_01", "PROD_02", "PROD_03"]:
        subset = generated_dataset[generated_dataset["product_id"] == pid]
        median_price = subset["price"].median()

        low_price_days = subset[subset["price"] < median_price]
        high_price_days = subset[subset["price"] > median_price]

        # Both groups must have sufficient observations
        assert len(low_price_days) >= 20, f"Insufficient low price days for {pid}."
        assert len(high_price_days) >= 20, f"Insufficient high price days for {pid}."

        mean_vol_low_price = low_price_days["sales_volume"].mean()
        mean_vol_high_price = high_price_days["sales_volume"].mean()

        assert mean_vol_low_price > mean_vol_high_price, (
            f"Law of Demand violated for {pid}: "
            f"Mean volume at low price ({mean_vol_low_price:.2f}) must exceed "
            f"mean volume at high price ({mean_vol_high_price:.2f})."
        )


def test_promotion_impact(generated_dataset: pd.DataFrame) -> None:
    """Verify promotional days have a statistically positive impact on sales volume.

    Args:
        generated_dataset: Synthetic dataset fixture.
    """
    # Promotion flag must only contain binary values (0 or 1)
    unique_flags = set(generated_dataset["promotion_flag"].unique())
    assert unique_flags.issubset({0, 1}), f"Invalid flags found: {unique_flags}."

    for pid in ["PROD_01", "PROD_02", "PROD_03"]:
        subset = generated_dataset[generated_dataset["product_id"] == pid]
        promo_days = subset[subset["promotion_flag"] == 1]
        non_promo_days = subset[subset["promotion_flag"] == 0]

        assert len(promo_days) > 0, f"No promotion days found for {pid}."
        assert len(non_promo_days) > 0, f"No non-promotion days found for {pid}."

        # Average sales volume on promotion days must be higher than non-promotion days
        mean_promo_volume = promo_days["sales_volume"].mean()
        mean_non_promo_volume = non_promo_days["sales_volume"].mean()

        assert mean_promo_volume > mean_non_promo_volume, (
            f"Promotion lift absent for {pid}: "
            f"Promo volume ({mean_promo_volume:.2f}) <= Non-promo volume ({mean_non_promo_volume:.2f})."
        )

